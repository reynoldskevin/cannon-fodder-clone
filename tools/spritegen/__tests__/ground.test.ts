import { describe, it, expect, beforeAll } from 'vitest'
import { mkdtempSync, existsSync, readFileSync, cpSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { buildSprites, GROUND_TEXTURES, PROPS, SpritegenError } from '../index'

/**
 * Ticket 034 — three tileable ground textures, not one.
 *
 * `floor.png` has been kept OUT of the atlas since ticket 004, and the reason
 * has not changed: `RepeatWrapping` wraps a whole texture, so an image that has
 * to tile cannot be a rect inside a packed sheet. Water and the bridge tile for
 * the same reason and stay out for the same reason.
 *
 * THE MANIFEST'S `floor` BECOMES `ground`, replacing it rather than sitting
 * beside it. Two spellings of one idea is how a manifest rots, and both
 * consumers — this tool and `src/app/main.ts` — are ours and are regenerated by
 * the build. Hence the version bump.
 */

const repoRoot = resolve(__dirname, '../../..')
const SOURCE = join(repoRoot, 'assets/source/sprites')

/**
 * Listed literally rather than imported from `../index`, matching `assets.test.ts`
 * and for its stated reason: this file is ground truth about what art exists on
 * disk, so a texture dropped from the pipeline's own list must fail here rather
 * than quietly narrow the test.
 */
const EXPECTED = [
  { name: 'jungle', source: 'floor-jungle.png', file: 'floor.png' },
  { name: 'water', source: 'water.png', file: 'water.png' },
  { name: 'bridge', source: 'bridge.png', file: 'bridge.png' },
] as const

let outDir: string
let out: ReturnType<typeof buildSprites>
let manifest: Record<string, unknown>

beforeAll(() => {
  outDir = mkdtempSync(join(tmpdir(), 'spritegen-ground-'))
  out = buildSprites({ sourceDir: SOURCE, outDir })
  manifest = JSON.parse(readFileSync(join(outDir, 'sprites.manifest.json'), 'utf8'))
})

describe('the ground textures', () => {
  it('names all three, and only those', () => {
    expect([...GROUND_TEXTURES].sort()).toEqual(['bridge', 'jungle', 'water'])
  })

  it('emits a file for each, beside the atlas', () => {
    /**
     * Beside, not inside: `main.ts` resolves every manifest path against the
     * manifest's own URL, so a texture written anywhere else is a 404 at boot —
     * the same failure ticket 024's levels manifest learned the hard way.
     */
    for (const { file } of EXPECTED) {
      expect({ file, exists: existsSync(join(outDir, file)) }).toEqual({ file, exists: true })
    }
  })

  it('declares each one in the manifest, marked tileable', () => {
    const ground = out.manifest.ground
    for (const { name, file } of EXPECTED) {
      const entry = ground[name]
      expect({ name, file: entry.file, tileable: entry.tileable }).toEqual({
        name,
        file,
        tileable: true,
      })
    }
  })

  it('halves each one, exactly as the jungle floor has always been halved', () => {
    /**
     * All three sources are 1024x1024, so all three take the existing divisor
     * and the existing divisibility check with no special case. Halving an NxN
     * block of a tileable image leaves it tileable; a fractional box would not,
     * which is what that check exists to refuse.
     */
    for (const { name } of EXPECTED) {
      const entry = out.manifest.ground[name]
      expect({ name, width: entry.width, height: entry.height }).toEqual({
        name,
        width: 512,
        height: 512,
      })
    }
  })

  it('and the declared size is the size of the file on disk', () => {
    // A manifest that lies about a texture's dimensions is worse than one that
    // omits it: the consumer trusts it and computes UVs from a wrong number.
    for (const { name, file } of EXPECTED) {
      const png = readFileSync(join(outDir, file))
      // IHDR: width and height are big-endian 32-bit at byte offsets 16 and 20.
      const width = png.readUInt32BE(16)
      const height = png.readUInt32BE(20)
      const entry = out.manifest.ground[name]
      expect({ name, width, height }).toEqual({ name, width: entry.width, height: entry.height })
    }
  })

  it('bumps the manifest version, because `floor` is gone rather than deprecated', () => {
    expect(manifest.version).toBe(2)
    expect(manifest.floor).toBeUndefined()
    expect(Object.keys(manifest.ground as Record<string, unknown>).sort()).toEqual([
      'bridge',
      'jungle',
      'water',
    ])
  })

  it('leaves the atlas alone — no ground texture is packed into it', () => {
    /**
     * The one property that makes all of this work. A tiling texture inside the
     * atlas would wrap the WHOLE SHEET on every repeat, so the river would be
     * paved with soldiers.
     */
    /**
     * ASSERTED AGAINST `PROPS`, NOT AGAINST A COPY OF IT. This used to spell the
     * seven prop names out, which made every addition to the art a failure here —
     * ticket 053 added `grenade` and `rocket` and broke a case about GROUND
     * TEXTURES, which is a false alarm in the most expensive place to get one.
     * The claim is that the atlas holds the props and nothing but the props; the
     * list of props is not this suite's business.
     */
    expect(Object.keys(out.manifest.props).sort()).toEqual([...PROPS].sort())
    for (const name of GROUND_TEXTURES) {
      expect({ name, packed: name in out.manifest.props }).toEqual({ name, packed: false })
    }
  })
})

describe('a missing ground texture stops the build and says which one', () => {
  it('names the file and the texture, rather than failing generically', () => {
    /**
     * NOT A SILENT FALLBACK TO THE JUNGLE. A river quietly drawn as jungle floor
     * is precisely the "looks plausible, is wrong" outcome that produced ticket
     * 033 — the bridge rendered as trees because nothing anywhere said
     * otherwise. Three textures means three ways to get this wrong, so the error
     * has to name which.
     */
    const partial = mkdtempSync(join(tmpdir(), 'spritegen-partial-'))
    cpSync(SOURCE, partial, { recursive: true })
    rmSync(join(partial, 'water.png'))

    let error: unknown
    try {
      buildSprites({ sourceDir: partial, outDir: mkdtempSync(join(tmpdir(), 'spritegen-out-')) })
    } catch (caught) {
      error = caught
    }
    rmSync(partial, { recursive: true, force: true })

    expect(error).toBeInstanceOf(SpritegenError)
    const message = error instanceof Error ? error.message : ''
    expect(message).toContain('water.png')
  })
})
